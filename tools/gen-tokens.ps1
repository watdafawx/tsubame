<#
.SYNOPSIS
  Generates mocks/tokens.css and mocks/generated/theme.rs from mocks/tokens.json.

.DESCRIPTION
  tokens.json is the single source of truth for Tsubame's look (see PLAN.md section 5).
  Outputs (commit them):
    mocks/tokens.css          CSS variables, dark (default) and light, for the HTML mocks
    mocks/generated/theme.rs  `pub struct Theme` + `pub const DARK` / `LIGHT` for the app
                              (stays here until a later task wires it into a crate)

  -Check   also print a WCAG contrast table and exit 1 if a text pair is below 4.5:1.
  No Node or Python needed. Works on Windows PowerShell 5.1 and pwsh 7.

.EXAMPLE
  pwsh -NoProfile -File tools/gen-tokens.ps1 -Check
#>
[CmdletBinding()]
param(
  [switch]$Check,
  [string]$Tokens = '',
  [string]$OutDir = ''
)
$ErrorActionPreference = 'Stop'
$inv = [Globalization.CultureInfo]::InvariantCulture

$root = Split-Path -Parent $PSScriptRoot
if (-not $Tokens) { $Tokens = Join-Path $root 'mocks\tokens.json' }
if (-not $OutDir) { $OutDir = Join-Path $root 'mocks' }
$genDir = Join-Path $OutDir 'generated'
New-Item -ItemType Directory -Force -Path $genDir | Out-Null

$t = Get-Content -Raw -Encoding UTF8 $Tokens | ConvertFrom-Json

# metric groups: json group name -> (also the css/rust prefix)
$metricGroups = @('space', 'radius', 'font_size', 'height', 'icon', 'layout')

function Get-Props($obj) {
  # ordered (key, value) pairs, skipping _comment keys
  foreach ($p in $obj.PSObject.Properties) {
    if ($p.Name.StartsWith('_')) { continue }
    [pscustomobject]@{ Key = $p.Name; Value = $p.Value }
  }
}

function Test-Hex($s, $where) {
  if ($s -notmatch '^#[0-9a-fA-F]{6}$') { throw "bad colour '$s' at $where (need #RRGGBB)" }
}

function Format-Num($v) {
  $s = ([double]$v).ToString('0.###', $inv)
  if ($s -notmatch '\.') { $s += '.0' }
  return $s
}

function Format-FontStack($names, $generic) {
  (($names | ForEach-Object { '"' + $_ + '"' }) -join ', ') + ', ' + $generic
}

# ---- validate: both themes must define the same colour keys ----
$themeNames = @($t.themes.PSObject.Properties.Name)
if ($themeNames[0] -ne 'dark') { throw "first theme must be 'dark' (it is the CSS default)" }
$colorKeys = @((Get-Props $t.themes.dark).Key)
foreach ($tn in $themeNames) {
  $keys = @((Get-Props $t.themes.$tn).Key)
  $diff = Compare-Object $colorKeys $keys
  if ($diff) { throw "theme '$tn' keys differ from 'dark': $($diff.InputObject -join ', ')" }
  foreach ($p in (Get-Props $t.themes.$tn)) { Test-Hex $p.Value "themes.$tn.$($p.Key)" }
}
foreach ($k in 'navy', 'cream', 'red') { Test-Hex $t.brand.$k "brand.$k" }

function Cn($s) { $s.Replace('_', '-') }

# ---------------------------------------------------------------- CSS
$css = New-Object System.Text.StringBuilder
[void]$css.AppendLine('/* GENERATED by tools/gen-tokens.ps1 from mocks/tokens.json. Do not edit. */')
[void]$css.AppendLine('/* Default is dark. Light: <html data-theme="light">. Sizes are logical px (1:1 at 100%). */')
[void]$css.AppendLine(':root {')
[void]$css.AppendLine('  --font-ui: ' + (Format-FontStack $t.font.ui 'system-ui, sans-serif') + ';')
[void]$css.AppendLine('  --font-mono: ' + (Format-FontStack $t.font.mono 'monospace') + ';')
foreach ($p in (Get-Props $t.brand)) { [void]$css.AppendLine("  --brand-$($p.Key): $($p.Value);") }
foreach ($g in $metricGroups) {
  foreach ($p in (Get-Props $t.$g)) {
    $px = ([double]$p.Value).ToString('0.###', $inv)
    [void]$css.AppendLine("  --$(Cn $g)-$(Cn $p.Key): ${px}px;")
  }
}
[void]$css.AppendLine('}')
foreach ($tn in $themeNames) {
  $sel = if ($tn -eq 'dark') { ':root, :root[data-theme="dark"]' } else { ":root[data-theme=`"$tn`"]" }
  [void]$css.AppendLine($sel + ' {')
  [void]$css.AppendLine("  color-scheme: $tn;")
  foreach ($p in (Get-Props $t.themes.$tn)) { [void]$css.AppendLine("  --c-$(Cn $p.Key): $($p.Value);") }
  [void]$css.AppendLine('}')
}
$cssPath = Join-Path $OutDir 'tokens.css'
[IO.File]::WriteAllText($cssPath, ($css.ToString() -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))

# ---------------------------------------------------------------- Rust
function RsHex($s) { '0x' + $s.Substring(1).ToUpperInvariant() }

$metricFields = New-Object System.Collections.Generic.List[object]
foreach ($g in $metricGroups) {
  foreach ($p in (Get-Props $t.$g)) {
    $metricFields.Add([pscustomobject]@{ Name = "${g}_$($p.Key)"; Value = $p.Value; Group = $g })
  }
}

$rs = New-Object System.Text.StringBuilder
[void]$rs.AppendLine('// GENERATED by tools/gen-tokens.ps1 from mocks/tokens.json. Do not edit.')
[void]$rs.AppendLine('//')
[void]$rs.AppendLine('// Colours are 0xRRGGBB (no alpha). Metrics are logical px (DIP, f32) at 100% scale;')
[void]$rs.AppendLine('// the render target applies the DPI. Not part of any crate yet: a later task wires it in.')
[void]$rs.AppendLine('#![allow(dead_code)]')
[void]$rs.AppendLine('')
[void]$rs.AppendLine('/// UI font families, first match wins (DirectWrite fallback order).')
[void]$rs.AppendLine('pub const FONT_UI: &[&str] = &[' + (($t.font.ui | ForEach-Object { '"' + $_ + '"' }) -join ', ') + '];')
[void]$rs.AppendLine('pub const FONT_MONO: &[&str] = &[' + (($t.font.mono | ForEach-Object { '"' + $_ + '"' }) -join ', ') + '];')
[void]$rs.AppendLine('')
[void]$rs.AppendLine('pub const BRAND_NAVY: u32 = ' + (RsHex $t.brand.navy) + ';')
[void]$rs.AppendLine('pub const BRAND_CREAM: u32 = ' + (RsHex $t.brand.cream) + ';')
[void]$rs.AppendLine('pub const BRAND_RED: u32 = ' + (RsHex $t.brand.red) + ';')
[void]$rs.AppendLine('')
[void]$rs.AppendLine('#[derive(Clone, Copy, Debug, PartialEq)]')
[void]$rs.AppendLine('pub struct Theme {')
[void]$rs.AppendLine('    pub name: &''static str,')
[void]$rs.AppendLine('    // colours (0xRRGGBB)')
foreach ($k in $colorKeys) { [void]$rs.AppendLine("    pub ${k}: u32,") }
$lastGroup = ''
foreach ($m in $metricFields) {
  if ($m.Group -ne $lastGroup) { [void]$rs.AppendLine("    // metrics: $($m.Group) (logical px)"); $lastGroup = $m.Group }
  [void]$rs.AppendLine("    pub $($m.Name): f32,")
}
[void]$rs.AppendLine('}')
[void]$rs.AppendLine('')
foreach ($tn in $themeNames) {
  [void]$rs.AppendLine("pub const $($tn.ToUpperInvariant()): Theme = Theme {")
  [void]$rs.AppendLine("    name: `"$tn`",")
  foreach ($p in (Get-Props $t.themes.$tn)) { [void]$rs.AppendLine("    $($p.Key): $(RsHex $p.Value),") }
  foreach ($m in $metricFields) { [void]$rs.AppendLine("    $($m.Name): $(Format-Num $m.Value),") }
  [void]$rs.AppendLine('};')
  [void]$rs.AppendLine('')
}
[void]$rs.AppendLine('impl Theme {')
[void]$rs.AppendLine('    /// "dark" or "light"; anything else gives DARK.')
[void]$rs.AppendLine('    pub const fn by_name(name: &str) -> &''static Theme {')
[void]$rs.AppendLine('        match name.as_bytes() {')
[void]$rs.AppendLine('            b"light" => &LIGHT,')
[void]$rs.AppendLine('            _ => &DARK,')
[void]$rs.AppendLine('        }')
[void]$rs.AppendLine('    }')
[void]$rs.AppendLine('}')
$rsPath = Join-Path $genDir 'theme.rs'
[IO.File]::WriteAllText($rsPath, ($rs.ToString() -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))

# ---- the kit's copy: same Theme + DARK/LIGHT, inside crates/tsubame-ui (used by the app) ----
# (only written for the default output dir; -OutDir runs, e.g. tests, leave the crate alone)
$kitPath = ''
if (-not $PSBoundParameters.ContainsKey('OutDir')) {
  $kitPath = Join-Path $root 'crates\tsubame-ui\src\theme_generated.rs'
  $kit = $rs.ToString()
  $kit = $kit.Replace('// the render target applies the DPI. Not part of any crate yet: a later task wires it in.', '// the render target applies the DPI. Hand-written helpers live in theme.rs.')
  $kit = $kit.Replace('#![allow(dead_code)]', '#![allow(dead_code)]')
  [IO.File]::WriteAllText($kitPath, ($kit -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
}

Write-Host "wrote $cssPath"
Write-Host "wrote $rsPath"
if ($kitPath) { Write-Host "wrote $kitPath" }

# ---------------------------------------------------------------- contrast check
function Get-Lum($hex) {
  $v = @()
  foreach ($i in 1, 3, 5) {
    $c = [Convert]::ToInt32($hex.Substring($i, 2), 16) / 255.0
    if ($c -le 0.03928) { $v += $c / 12.92 } else { $v += [Math]::Pow(($c + 0.055) / 1.055, 2.4) }
  }
  0.2126 * $v[0] + 0.7152 * $v[1] + 0.0722 * $v[2]
}
function Get-Contrast($a, $b) {
  $la = Get-Lum $a; $lb = Get-Lum $b
  $hi = [Math]::Max($la, $lb); $lo = [Math]::Min($la, $lb)
  ($hi + 0.05) / ($lo + 0.05)
}

if ($Check) {
  # (foreground, backgrounds, minimum ratio, kind)
  $rules = @(
    @{ fg = 'text';       bg = 'bg', 'panel', 'popup', 'field', 'row', 'row_alt', 'hover', 'selected', 'selected_inactive'; min = 4.5 },
    @{ fg = 'text_dim';   bg = 'bg', 'panel', 'popup', 'field', 'row', 'row_alt', 'hover', 'selected', 'selected_inactive'; min = 4.5 },
    @{ fg = 'accent';     bg = 'bg', 'panel', 'popup', 'field', 'row', 'row_alt', 'hover'; min = 4.5 },
    @{ fg = 'danger';     bg = 'bg', 'panel', 'popup', 'field', 'row', 'row_alt', 'hover', 'selected'; min = 4.5 },
    @{ fg = 'text';       bg = 'highlight'; min = 4.5 },
    @{ fg = 'on_accent';  bg = 'accent'; min = 4.5 },
    @{ fg = 'on_danger';  bg = 'danger_fill'; min = 4.5 },
    @{ fg = 'focus';      bg = 'row', 'row_alt', 'selected', 'hover', 'field', 'panel'; min = 3.0 },
    @{ fg = 'scrollbar';  bg = 'row'; min = 1.5 },
    @{ fg = 'text_disabled'; bg = 'panel', 'popup', 'row'; min = 0 }
  )
  $fail = 0
  foreach ($tn in $themeNames) {
    $th = $t.themes.$tn
    Write-Host ''
    Write-Host "== contrast, theme: $tn ==" -ForegroundColor Cyan
    foreach ($r in $rules) {
      $fgHex = $th.($r.fg)
      foreach ($bgName in $r.bg) {
        $bgHex = $th.$bgName
        $cr = Get-Contrast $fgHex $bgHex
        $ok = $cr -ge $r.min
        $tag = if ($r.min -eq 0) { 'info' } elseif ($ok) { 'ok  ' } else { 'FAIL' }
        if (-not $ok -and $r.min -gt 0) { $fail++ }
        $line = ('{0}  {1,-14} {2} on {3,-18} {4}  {5,5:N2}  (min {6})' -f $tag, $r.fg, $fgHex, $bgName, $bgHex, $cr, $r.min)
        if ($tag -eq 'FAIL') { Write-Host $line -ForegroundColor Red } else { Write-Host $line }
      }
    }
  }
  Write-Host ''
  if ($fail -gt 0) { Write-Host "$fail pair(s) below minimum" -ForegroundColor Red; exit 1 }
  Write-Host 'all contrast pairs pass' -ForegroundColor Green
}
